class CargoTests(unittest.TestCase):
    def test_every_test_line_gets_its_package_target_and_result(self):
        cases = tc.parse_cargo(CARGO_OUTPUT, TARGETS)
        got = [(c.package, c.target, c.name, c.result) for c in cases]
        self.assertEqual(got, [
            ("ipmc-core", "unit tests", "link::tests::first", tc.PASS),
            ("ipmc-core", "unit tests", "link::tests::second", tc.FAIL),
            ("ipmc-core", "unit tests", "sdr::tests::third", tc.IGNORED),
            ("ipmc-core", "commands_doc", "the_doc_matches", tc.PASS),
            ("ipmc-core", "doc tests", "src\\lib.rs - checksum (line 5)", tc.PASS),
        ])

    def test_read_targets_normalises_names_and_paths(self):
        metadata = json.dumps({"packages": [{"name": "ipmc-ext", "targets": [
            {"name": "ipmc-ext", "src_path": "C:\\r\\crates\\ipmc-ext\\src\\lib.rs"}]}]})
        self.assertEqual(tc.read_targets(metadata), [("ipmc-ext", "ipmc_ext", "C:/r/crates/ipmc-ext/src/lib.rs")])

    def test_a_binary_and_a_library_of_one_package_are_told_apart_by_their_source_file(self):
        text = "     Running unittests src\\main.rs (target\\debug\\deps\\ipmc_emu-0123456789abcdef.exe)\n" \
               "test replay::tests::one ... ok\n"
        self.assertEqual(tc.parse_cargo(text, TARGETS)[0].package, "ipmc-emu")


class UnittestTests(unittest.TestCase):
    def test_results_after_noise_and_skips_are_read(self):
        suite = tc.parse_unittest(UNITTEST_OUTPUT, "tools/x")
        got = [(c.target, c.name, c.result) for c in suite.cases]
        self.assertEqual(got, [
            ("test_x.First", "test_a", tc.PASS),
            ("test_x.First", "test_b", tc.PASS),
            ("test_x.Second", "test_c", tc.IGNORED),
            ("test_x.Second", "test_d", tc.FAIL),
            ("test_x.Second", "test_e", tc.PASS),
        ])
        self.assertEqual(suite.error, "")

    def test_a_count_that_disagrees_with_ran_is_an_error(self):
        suite = tc.parse_unittest(UNITTEST_OUTPUT.replace("Ran 5", "Ran 6"), "tools/x")
        self.assertIn("parsed 5", suite.error)


class ReplayTests(unittest.TestCase):
    LINE = "PASS requests=309 answered=309 match=44 same_cc=42 cc_diff=134 not_implemented=89 unanswered=0"

    def test_the_expected_numbers_pass(self):
        self.assertEqual(tc.parse_replay(self.LINE, (44, 42, 134, 89), "t").status, tc.PASS)

    def test_other_numbers_fail(self):
        self.assertEqual(tc.parse_replay(self.LINE, (66, 46, 197, 0), "t").status, tc.FAIL)

